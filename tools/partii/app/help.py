def report_help(lines):
    """The help of every line of one report: its place in the form, and whether its parts add up to it in this report."""
    by_code = {r["code"]: r for r in lines}
    out = []
    for r in lines:
        parts = [x for x in lines if x["parent"] == r["code"]]
        checks = []
        if r["code"] == "income.total":
            text = "Обобщен ред: всички набрани средства за кампанията. Редовете над него вече са включени в сумата, не ги прибавяйте отново."
        elif r["code"] == "expense.total":
            text = "Обобщен ред: всички разходи по кампанията. Редовете над него вече са включени в сумата."
        elif r["code"] == "expense.unpaid":
            text = "Част от разходите: задължения за получени стоки и услуги, които не са платени към датата на отчета. Вече е в общия размер на разходите."
        elif r["code"] == "in_kind.total":
            text = "Стойността на получените непарични средства и дарения. Показва се отделно от паричните."
        elif r["code"] == "total":
            text = "Общият размер на финансирането на кампанията: разходите плюс стойността на непаричните средства."
        elif parts:
            text = "Обобщен ред: включва подредовете под себе си. Те може да са частична разбивка."
        elif r["parent"] and r["parent"] in by_code:
            text = "Подред на „" + by_code[r["parent"]]["label"] + "“. Сумата му вече е в обобщения ред."
        else:
            text = "Ред от формата на отчета, без подредове."
        if parts and r["amount"] is not None and all(x["amount"] is not None for x in parts):
            total = sum((x["amount"] for x in parts), Decimal(0))
            if abs(total - r["amount"]) > Decimal("0.01"):
                checks.append(f"В този отчет подредовете дават общо {total:,.2f}".replace(",", " ").replace(".", ",")
                              + f", а редът е {r['amount']:,.2f}".replace(",", " ").replace(".", ",") + ". Така е подаден: не го поправяме.")
        if r["amount"] is None:
            checks.append("В този отчет редът не е попълнен (във файла стои −1 или е празен). Това не е нула.")
        out.append(dict(title=r["label"], text=text, example="Условен пример: обобщен ред 100 с подредове 60 и 40 значи, че 60 и 40 вече са в 100-те.", checks=checks, source=SRC))
    return out
